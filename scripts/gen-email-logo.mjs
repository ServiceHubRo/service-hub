// Draws the wordmark used at the top of every email (SERVICE- in warm white, HUB in amber, Inter
// 800) as a PNG at 3× and writes it, base64, to supabase/functions/_shared/emailLogo.ts, which the
// email-logo Edge Function serves. An image because the Gmail app on iPhone repaints the colors of
// text in dark mode, never those of images. Run with `node scripts/gen-email-logo.mjs`; the output
// is committed.
import { chromium } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';

const SCALE = 3;
const font = (await readFile('node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2')).toString('base64');
const html = `<!doctype html><html><head><meta charset="utf-8"><style>
  @font-face { font-family: Inter; font-weight: 100 900; src: url(data:font/woff2;base64,${font}) format('woff2'); }
  body { margin: 0; background: transparent; }
  #w { display: inline-block; padding: 1px 0; font: 800 20px/1 Inter, sans-serif; letter-spacing: -0.01em; white-space: nowrap; color: #EAE8E2; }
  #w span { color: #F5A524; }
</style></head><body><div id="w">SERVICE-<span>HUB</span></div></body></html>`;

const browser = await chromium.launch(
  process.env.PLAYWRIGHT_CHROMIUM_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH } : {},
);
const page = await browser.newPage({ deviceScaleFactor: SCALE });
await page.setContent(html);
await page.evaluate(() => document.fonts.ready);
const box = await page.locator('#w').boundingBox();
const png = await page.locator('#w').screenshot({ omitBackground: true });
await browser.close();

const width = Math.ceil(box.width);
const height = Math.ceil(box.height);
await writeFile(
  'supabase/functions/_shared/emailLogo.ts',
  `// Generated by scripts/gen-email-logo.mjs — do not edit.\n` +
    `export const LOGO_WIDTH = ${width};\nexport const LOGO_HEIGHT = ${height};\n` +
    `export const LOGO_PNG_BASE64 =\n  '${png.toString('base64')}';\n`,
);
process.stdout.write(`email logo: ${width}×${height} (${png.length} bytes at ${SCALE}×)\n`);
