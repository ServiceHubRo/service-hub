// Draws every email button (supabase/functions/_shared/emailButtonLabels.ts) as a PNG at 3×: the
// amber button with its dark text, as in the app. Writes the sizes to emailButtonSizes.ts (read by
// emails.ts) and the pictures, base64, to emailButtonImages.ts (served by the email-logo Edge
// Function, `?b=<name>`). Images because the Gmail app on iPhone repaints the colors of an HTML
// button in dark mode (amber turns brown), never those of an image. Run with
// `node scripts/gen-email-buttons.mjs` after changing a button text; the output is committed.
import { chromium } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import { EMAIL_BUTTON_LABELS, buttonSlug } from '../supabase/functions/_shared/emailButtonLabels.ts';

const SCALE = 3;
const font = (await readFile('node_modules/@fontsource-variable/inter/files/inter-latin-ext-wght-normal.woff2')).toString('base64');
const fontLatin = (await readFile('node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2')).toString('base64');

const escape = (s) => s.replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' })[c]);
const browser = await chromium.launch(
  process.env.PLAYWRIGHT_CHROMIUM_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH } : {},
);
const page = await browser.newPage({ deviceScaleFactor: SCALE });

const sizes = {};
const images = {};
for (const label of EMAIL_BUTTON_LABELS) {
  // The same button as the HTML one in emails.ts: 15 px bold, 13 × 22 px padding, 10 px corners.
  await page.setContent(`<!doctype html><html><head><meta charset="utf-8"><style>
    @font-face { font-family: Inter; font-weight: 100 900; src: url(data:font/woff2;base64,${fontLatin}) format('woff2'); unicode-range: U+0000-00FF; }
    @font-face { font-family: Inter; font-weight: 100 900; src: url(data:font/woff2;base64,${font}) format('woff2'); unicode-range: U+0100-024F; }
    body { margin: 0; background: transparent; }
    #b { display: inline-block; padding: 13px 22px; border-radius: 10px; background: #F5A524; color: #151515;
         font: 700 15px/18px Inter, sans-serif; white-space: nowrap; }
  </style></head><body><div id="b">${escape(label)}</div></body></html>`);
  await page.evaluate(() => document.fonts.ready);
  const box = await page.locator('#b').boundingBox();
  const png = await page.locator('#b').screenshot({ omitBackground: true });
  const slug = buttonSlug(label);
  sizes[label] = { slug, width: Math.ceil(box.width), height: Math.ceil(box.height) };
  images[slug] = png.toString('base64');
}
await browser.close();

await writeFile(
  'supabase/functions/_shared/emailButtonSizes.ts',
  `// Generated by scripts/gen-email-buttons.mjs — do not edit.\n` +
    `export const EMAIL_BUTTON_SIZES: Record<string, { slug: string; width: number; height: number }> = ${JSON.stringify(sizes, null, 2)};\n`,
);
await writeFile(
  'supabase/functions/_shared/emailButtonImages.ts',
  `// Generated by scripts/gen-email-buttons.mjs — do not edit.\n` +
    `export const EMAIL_BUTTON_PNG_BASE64: Record<string, string> = {\n` +
    Object.entries(images)
      .map(([slug, b64]) => `  '${slug}':\n    '${b64}',`)
      .join('\n') +
    `\n};\n`,
);
const bytes = Object.values(images).reduce((n, b) => n + (b.length * 3) / 4, 0);
process.stdout.write(`email buttons: ${EMAIL_BUTTON_LABELS.length} (${Math.round(bytes / 1024)} KB at ${SCALE}×)\n`);
