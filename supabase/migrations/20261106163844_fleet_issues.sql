-- ------------------------------------------------------------------ report
create function public.fleet_report_issue(p_company uuid, p_issue uuid, p_fields jsonb, p_request_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_seen jsonb;
  f jsonb := coalesce(p_fields, '{}'::jsonb);
  v_vehicle uuid := public.try_uuid(f->>'vehicle_id');
  v_cv public.company_vehicles%rowtype;
  v_kind text := f->>'kind';
  v_title text := btrim(coalesce(f->>'title', ''));
  v_description text := nullif(btrim(coalesce(f->>'description', '')), '');
  v_day date;
  v_booking uuid := public.try_uuid(nullif(f->>'booking_id', ''));
  v_photos text[];
  v_row public.fleet_issues%rowtype;
  v_result jsonb;
begin
  perform public.require_fleet_client();
  v_seen := public.request_begin(p_request_id, 'fleet_report_issue');
  if v_seen is not null then
    return v_seen;
  end if;
  if public.company_role(p_company) is null then
    perform public.fail('company_not_found');
  end if;
  if public.company_read_only(p_company) then
    perform public.fail('fleet_read_only');
  end if;
  if p_issue is null then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'id'));
  end if;

  if v_kind is null or v_kind not in ('defect', 'damage', 'accident', 'technical', 'other') then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'kind'));
  end if;
  if char_length(v_title) not between 3 and 120 then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'title'));
  end if;
  if char_length(v_description) > 2000 then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'description'));
  end if;
  begin
    v_day := (f->>'happened_on')::date;
  exception when others then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'happened_on'));
  end;
  if v_day is null or v_day > public.bucharest_today() or v_day < date '2000-01-01' then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'happened_on'));
  end if;

  -- One request at a time per vehicle; the vehicle must be the company's and still in the fleet.
  select * into v_cv from public.company_vehicles cv where cv.id = v_vehicle and cv.company_id = p_company for update;
  if not found then
    perform public.fail('vehicle_not_found');
  end if;
  if v_cv.archived_at is not null then
    perform public.fail('vehicle_archived');
  end if;
  if not public.fleet_issue_can_report(p_company, v_vehicle) then
    perform public.fail('not_allowed');
  end if;
  if v_booking is not null and not exists (
    select 1 from public.bookings b where b.id = v_booking and b.company_id = p_company and b.company_vehicle_id = v_vehicle) then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'booking'));
  end if;
  if exists (select 1 from public.fleet_issues x where x.id = p_issue) then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'id'));
  end if;

  v_photos := public.fleet_issue_check_photos(p_company, v_vehicle, p_issue, f->'photos');
  if cardinality(v_photos) > 6 then
    perform public.fail('too_many_photos');
  end if;

  insert into public.fleet_issues (id, company_id, vehicle_id, vehicle_label, kind, title, description, happened_on, booking_id, photos, reported_by)
  values (p_issue, p_company, v_vehicle, jsonb_build_object('plate', v_cv.plate, 'make', v_cv.make, 'model', v_cv.model),
          v_kind, v_title, v_description, v_day, v_booking, v_photos, auth.uid())
  returning * into v_row;
  insert into public.fleet_issue_events (issue_id, from_status, to_status, booking_id, photos_added, by_user)
  values (v_row.id, null, 'new', v_booking, cardinality(v_photos), auth.uid());
  perform public.company_audit(p_company, 'issue_reported', 'issue', v_row.id, null, public.fleet_issue_json(v_row));

  v_result := public.fleet_issue_json(v_row);
  perform public.request_finish(p_request_id, v_result);
  return v_result;
end
$$;

-- ------------------------------------------------------------------ follow up (issues.manage)
-- Fields: status, note, booking_id (present = set it; null unlinks), add_photos. Title and description
-- stay as reported.
create function public.fleet_update_issue(p_issue uuid, p_fields jsonb, p_request_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_seen jsonb;
  f jsonb := coalesce(p_fields, '{}'::jsonb);
  v_before public.fleet_issues%rowtype;
  v_row public.fleet_issues%rowtype;
  v_status text;
  v_note text := nullif(btrim(coalesce(f->>'note', '')), '');
  v_booking uuid;
  v_link boolean := f ? 'booking_id';
  v_photos text[];
  v_result jsonb;
begin
  perform public.require_fleet_client();
  v_seen := public.request_begin(p_request_id, 'fleet_update_issue');
  if v_seen is not null then
    return v_seen;
  end if;
  select * into v_before from public.fleet_issues x where x.id = p_issue for update;
  if not found or not public.fleet_issue_can_read(v_before) then
    perform public.fail('issue_not_found');
  end if;
  if not public.fleet_can(v_before.company_id, 'issues.manage') then
    perform public.fail('not_allowed');
  end if;
  if public.company_read_only(v_before.company_id) then
    perform public.fail('fleet_read_only');
  end if;

  v_status := coalesce(nullif(f->>'status', ''), v_before.status);
  if v_status not in ('new', 'in_review', 'scheduled', 'resolved', 'closed') then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'status'));
  end if;
  if char_length(v_note) > 500 then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'note'));
  end if;
  if v_link then
    v_booking := public.try_uuid(nullif(f->>'booking_id', ''));
    if nullif(f->>'booking_id', '') is not null and (v_booking is null or not exists (
      select 1 from public.bookings b where b.id = v_booking and b.company_id = v_before.company_id
        and b.company_vehicle_id = v_before.vehicle_id)) then
      perform public.fail('issue_invalid', jsonb_build_object('field', 'booking'));
    end if;
  else
    v_booking := v_before.booking_id;
  end if;
  v_photos := public.fleet_issue_check_photos(v_before.company_id, v_before.vehicle_id, v_before.id, f->'add_photos');
  select coalesce(array_agg(p order by n), '{}') into v_photos
  from unnest(v_photos) with ordinality u(p, n) where not (p = any (v_before.photos));
  if cardinality(v_before.photos) + cardinality(v_photos) > 6 then
    perform public.fail('too_many_photos');
  end if;
  if v_status = v_before.status and v_note is null and v_booking is not distinct from v_before.booking_id and cardinality(v_photos) = 0 then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'nothing'));
  end if;

  update public.fleet_issues set status = v_status, booking_id = v_booking, photos = photos || v_photos, updated_at = now()
  where id = p_issue
  returning * into v_row;
  insert into public.fleet_issue_events (issue_id, from_status, to_status, note, booking_id, photos_added, by_user)
  values (v_row.id, v_before.status, case when v_status <> v_before.status then v_status end, v_note,
          case when v_booking is distinct from v_before.booking_id then v_booking end, cardinality(v_photos), auth.uid());
  perform public.company_audit(v_row.company_id, 'issue_updated', 'issue', v_row.id, public.fleet_issue_json(v_before),
    public.fleet_issue_json(v_row) || jsonb_build_object('note', v_note));

  v_result := public.fleet_issue_json(v_row);
  perform public.request_finish(p_request_id, v_result);
  return v_result;
end
$$;

-- ------------------------------------------------------------------ one report with its history
create function public.fleet_issue_detail(p_issue uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_row public.fleet_issues%rowtype;
begin
  perform public.require_fleet_client();
  select * into v_row from public.fleet_issues x where x.id = p_issue;
  if not found or not public.fleet_issue_can_read(v_row) then
    perform public.fail('issue_not_found');
  end if;
  return public.fleet_issue_json(v_row) || jsonb_build_object(
    'events', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', e.id, 'from_status', e.from_status, 'to_status', e.to_status, 'note', e.note, 'booking_id', e.booking_id,
               'photos_added', e.photos_added, 'by_user', e.by_user,
               'by_name', (select p.name from public.profiles p where p.id = e.by_user), 'at', e.at) order by e.id)
      from public.fleet_issue_events e where e.issue_id = v_row.id), '[]'::jsonb));
end
$$;

revoke execute on function public.fleet_report_issue(uuid, uuid, jsonb, uuid), public.fleet_update_issue(uuid, jsonb, uuid),
  public.fleet_issue_detail(uuid) from public, anon;
grant execute on function public.fleet_report_issue(uuid, uuid, jsonb, uuid), public.fleet_update_issue(uuid, jsonb, uuid),
  public.fleet_issue_detail(uuid) to authenticated;

-- ------------------------------------------------------------------ the daily cleanup (service role only)
-- Unattached issue photos older than 48 hours. Only exact issue paths can be candidates.
create function public.fleet_issue_photo_orphans(p_limit int default 500)
returns setof text
language sql
stable
security definer
set search_path = ''
as $$
  select o.name from storage.objects o
  where o.bucket_id = 'fleet-files' and public.fleet_issue_path(o.name)
    and o.created_at < now() - interval '48 hours'
    and not exists (select 1 from public.fleet_issues i where i.photos @> array[o.name])
  order by o.created_at, o.name
  limit greatest(1, least(coalesce(p_limit, 500), 1000))
$$;

-- Checked again right before each delete.
create function public.fleet_issue_photo_orphan(p_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.fleet_issue_path(p_name)
    and exists (select 1 from storage.objects o where o.bucket_id = 'fleet-files' and o.name = p_name
                  and o.created_at < now() - interval '48 hours')
    and not exists (select 1 from public.fleet_issues i where i.photos @> array[p_name])
$$;
revoke execute on function public.fleet_issue_photo_orphans(int), public.fleet_issue_photo_orphan(text) from public, anon, authenticated;
grant execute on function public.fleet_issue_photo_orphans(int), public.fleet_issue_photo_orphan(text) to service_role;

-- Posted once a day by pg_cron, with the dispatcher's token (as kick_company_checks).
create function public.kick_fleet_files_cleanup()
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_url text;
  v_token text;
begin
  if to_regnamespace('net') is null then
    return false;
  end if;
  select dispatch_url, dispatch_token into v_url, v_token from public.push_config where id = 1;
  if v_url is null or v_url not like '%/dispatch-notifications%' then
    return false;
  end if;
  execute 'select net.http_post(url := $1, body := $2, headers := $3, timeout_milliseconds := 120000)'
    using replace(v_url, '/dispatch-notifications', '/fleet-files-cleanup'), '{}'::jsonb,
          jsonb_build_object('Content-Type', 'application/json', 'x-dispatch-token', v_token);
  return true;
end
$$;
revoke execute on function public.kick_fleet_files_cleanup() from public, anon, authenticated;

do $$
begin
  if to_regnamespace('cron') is not null then
    perform cron.schedule('sh_fleet_files_cleanup', '23 3 * * *', 'select public.kick_fleet_files_cleanup()');
  end if;
end
$$;

-- ------------------------------------------------------------------ the space's one read: the issues filled in
create or replace function public.fleet_overview(p_company uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_company public.companies%rowtype;
  v_role text;
  v_me uuid;
  v_all boolean;
  v_team boolean;
  v_money boolean;
  v_bookings boolean;
  v_issues boolean;
begin
  perform public.require_fleet_client();
  select * into v_company from public.companies c where c.id = p_company and c.archived_at is null;
  v_role := public.company_role(p_company);
  if v_company.id is null or v_role is null then
    perform public.fail('company_not_found');
  end if;
  v_me := public.my_member_id(p_company);
  v_all := public.fleet_can(p_company, 'vehicles.viewAll');
  v_team := public.fleet_can(p_company, 'members.manage') or public.fleet_can(p_company, 'vehicles.manage');
  v_money := public.fleet_can(p_company, 'costs.view');
  v_bookings := public.fleet_can(p_company, 'bookings.viewAll');
  v_issues := v_all or public.fleet_can(p_company, 'issues.manage');
  return jsonb_build_object(
    'company', jsonb_build_object(
      'id', v_company.id, 'name', v_company.name, 'vat_id', v_company.vat_id, 'plan_key', 'none',
      -- Money rules only for those who see money.
      'manager_approval_limit', case when v_money then v_company.manager_approval_limit end,
      'budget', jsonb_build_object(
        'monthly', case when v_money then v_company.budget_monthly end,
        'yearly', case when v_money then v_company.budget_yearly end)),
    'me', jsonb_build_object('member_id', v_me, 'role', v_role,
      -- The rights that apply: none on a plan without them (kept, they apply again after an upgrade).
      'extra_caps', to_jsonb(case when public.fleet_has_feature(p_company, 'member_rights')
                                  then (select m.extra_caps from public.company_members m where m.id = v_me) else '{}'::text[] end),
      'approval_limit', case when v_money then public.my_approval_limit(p_company) end),
    'vehicles', coalesce((
      select jsonb_agg(public.vehicle_json(cv) order by cv.created_at, cv.id)
      from public.company_vehicles cv
      where cv.company_id = p_company
        and (v_all or (cv.driver_member_id = v_me and cv.archived_at is null))
    ), '[]'::jsonb),
    'members', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', m.id, 'user_id', m.user_id, 'name', coalesce(p.name, ''),
               'email', lower(coalesce(u.email, m.invited_email)), 'role', m.role, 'accepted_at', m.accepted_at,
               'extra_caps', to_jsonb(m.extra_caps), 'approval_limit', case when v_money then m.approval_limit end)
             order by m.accepted_at nulls last, m.invited_at)
      from public.company_members m
      left join public.profiles p on p.id = m.user_id
      left join auth.users u on u.id = m.user_id
      where m.company_id = p_company and (v_team or m.user_id = auth.uid())
    ), '[]'::jsonb),
    -- The company's bookings (T63d): all for those who see all; a driver those of the vehicles
    -- assigned to them and their own, without amounts.
    'jobs', coalesce((
      select jsonb_agg(public.fleet_job_json(b, v_money) order by b.date desc, b.slot desc, b.id)
      from public.bookings b
      where b.company_id = p_company
        and (v_bookings
             or b.client_id = auth.uid()
             or b.company_vehicle_id in (
               select cv.id from public.company_vehicles cv
               where cv.company_id = p_company and cv.driver_member_id = v_me and cv.archived_at is null))
    ), '[]'::jsonb),
    -- M1: the company's own expenses; a member without costs.view (a driver) sees only the ones they added.
    'expenses', coalesce((
      select jsonb_agg(public.fleet_expense_json(e) order by e.day desc, e.created_at desc)
      from public.fleet_expenses e
      where e.company_id = p_company and e.deleted_at is null and (v_money or e.created_by = auth.uid())), '[]'::jsonb),
    -- M3: issues and incidents; all for vehicles.viewAll / issues.manage, otherwise the member's own reports
    -- and those of the vehicles assigned to them.
    'issues', coalesce((
      select jsonb_agg(public.fleet_issue_json(i) order by i.created_at desc, i.id)
      from public.fleet_issues i
      where i.company_id = p_company
        and (v_issues or i.reported_by = auth.uid()
             or i.vehicle_id in (select cv.id from public.company_vehicles cv where cv.company_id = p_company and cv.driver_member_id = v_me))
    ), '[]'::jsonb)
  );
end
$$;

