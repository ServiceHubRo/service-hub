-- M3 / T72 — issues and incidents (Eduard, 6 Nov 2026: approved in docs/FLEET_EXTENSION_PLAN.md §M3).
--
-- A member reports a defect, damage, an accident or a technical problem of a company vehicle, with up
-- to 6 photos; the company follows it (new → in review → scheduled → resolved → closed), links the
-- Service-Hub booking that fixes it and adds notes and photos. Every change in fleet_issue_events and
-- in company_audit_log. Title and description stay as reported.
--
-- Rights (fleet_can): report = `issues.report` on a vehicle the member sees (a driver: the vehicle
-- assigned to them) or `issues.manage`; change = `issues.manage` (admin, manager); read = the reporter
-- while a member, the vehicle's driver, `issues.manage`, `vehicles.viewAll` (the accountant reads).
--
-- Photos in the private bucket `fleet-files`, path `<company>/<vehicle>/issues/<issue>/<file>`. The M1
-- policies are replaced by variants that branch on the path: every other path (the receipts,
-- `<company>/<vehicle>/<file>`) keeps exactly the M1 rules. A photo is attached only by its uploader,
-- within 23 hours of the upload; an unattached photo older than 48 hours is deleted by the daily
-- `fleet-files-cleanup` Edge Function (Storage API). The 23 h / 48 h gap rules out a race between
-- attaching and cleaning.
--
-- Nothing existing is modified. Rollback: supabase/rollback/20261106163844_fleet_issues.sql (drops the
-- new tables and functions, restores fleet_overview and the three M1 policies verbatim; issues and
-- their history are lost, photos stay in storage).

create table public.fleet_issues (
  id uuid primary key,                                  -- generated by the app; also the photo folder
  company_id uuid not null references public.companies (id) on delete cascade,
  vehicle_id uuid not null references public.company_vehicles (id),   -- no cascade: history blocks deletion
  vehicle_label jsonb not null,                          -- plate/make/model at report time
  kind text not null check (kind in ('defect', 'damage', 'accident', 'technical', 'other')),
  title text not null check (char_length(btrim(title)) between 3 and 120),
  description text check (char_length(description) <= 2000),
  happened_on date not null check (happened_on >= date '2000-01-01'),
  status text not null default 'new' check (status in ('new', 'in_review', 'scheduled', 'resolved', 'closed')),
  booking_id uuid references public.bookings (id) on delete set null,
  photos text[] not null default '{}' check (cardinality(photos) <= 6),
  reported_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);
create index fleet_issues_company_idx on public.fleet_issues (company_id, created_at desc);
create index fleet_issues_vehicle_idx on public.fleet_issues (vehicle_id, created_at desc);
create index fleet_issues_photos_idx on public.fleet_issues using gin (photos);
alter table public.fleet_issues enable row level security;

create table public.fleet_issue_events (
  id bigint generated always as identity primary key,
  issue_id uuid not null references public.fleet_issues (id) on delete cascade,
  from_status text,
  to_status text,
  note text check (char_length(note) <= 500),
  booking_id uuid,
  photos_added int not null default 0,
  by_user uuid references public.profiles (id) on delete set null,
  at timestamptz not null default now()
);
create index fleet_issue_events_issue_idx on public.fleet_issue_events (issue_id, id);
alter table public.fleet_issue_events enable row level security;
-- RLS on, no grants, no policies: read through fleet_overview / fleet_issue_detail only.
revoke all on public.fleet_issues, public.fleet_issue_events from anon, authenticated;

-- ------------------------------------------------------------------ who may do what
-- Report on this vehicle: issues.manage, or issues.report on a vehicle the member sees (vehicles.viewAll,
-- or the vehicle assigned to them). Archived vehicles take no new reports.
create function public.fleet_issue_can_report(p_company uuid, p_vehicle uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select p_company is not null and p_vehicle is not null and exists (
    select 1 from public.company_vehicles cv
    where cv.id = p_vehicle and cv.company_id = p_company and cv.archived_at is null
      and (public.fleet_can(p_company, 'issues.manage')
           or (public.fleet_can(p_company, 'issues.report')
               and (public.fleet_can(p_company, 'vehicles.viewAll') or cv.driver_member_id = public.my_member_id(p_company)))))
$$;

-- Read a report: the reporter while a member, the vehicle's driver, issues.manage, vehicles.viewAll.
create function public.fleet_issue_can_read(p_issue public.fleet_issues)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.company_role(p_issue.company_id) is not null
    and (p_issue.reported_by = auth.uid()
         or public.fleet_can(p_issue.company_id, 'issues.manage')
         or public.fleet_can(p_issue.company_id, 'vehicles.viewAll')
         or exists (select 1 from public.company_vehicles cv where cv.id = p_issue.vehicle_id
                      and cv.driver_member_id = public.my_member_id(p_issue.company_id)))
$$;
revoke execute on function public.fleet_issue_can_report(uuid, uuid), public.fleet_issue_can_read(public.fleet_issues) from public, anon;
grant execute on function public.fleet_issue_can_report(uuid, uuid), public.fleet_issue_can_read(public.fleet_issues) to authenticated;

-- ------------------------------------------------------------------ the photos
-- `<company uuid>/<vehicle uuid>/issues/<issue uuid>/<file>`; nothing else is an issue photo. A receipt
-- (`<uuid>/<uuid>/<file>`) can never match.
create function public.fleet_issue_path(p_name text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select coalesce(p_name ~ ('^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/'
                         || '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/issues/'
                         || '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/[A-Za-z0-9._-]{1,120}$'), false)
$$;
grant execute on function public.fleet_issue_path(text) to authenticated, service_role;

-- Upload. Into the folder of an existing report: issues.manage of that company (adding photos). Into a
-- new folder: a member who may report on that vehicle, and never into a folder someone else already
-- uploaded to (another report's photos).
create function public.fleet_issue_photo_can_upload(p_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  f text[] := string_to_array(p_name, '/');
  v_company uuid := public.try_uuid(f[1]);
  v_vehicle uuid := public.try_uuid(f[2]);
  v_issue uuid := public.try_uuid(f[4]);
  i public.fleet_issues%rowtype;
begin
  if not public.fleet_issue_path(p_name) or auth.uid() is null then
    return false;
  end if;
  select * into i from public.fleet_issues x where x.id = v_issue;
  if found then
    return i.company_id = v_company and i.vehicle_id = v_vehicle and public.fleet_can(v_company, 'issues.manage');
  end if;
  return public.fleet_issue_can_report(v_company, v_vehicle)
    and not exists (select 1 from storage.objects o
                    where o.bucket_id = 'fleet-files' and split_part(o.name, '/', 3) = 'issues'
                      and split_part(o.name, '/', 4) = f[4] and o.owner is distinct from auth.uid());
end
$$;

-- Read. Attached to its report: whoever may read the report. Not attached (yet): only its uploader,
-- while still allowed to report on that vehicle (or issues.manage).
create function public.fleet_issue_photo_can_read(p_name text, p_owner uuid)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  f text[] := string_to_array(p_name, '/');
  v_company uuid := public.try_uuid(f[1]);
  v_vehicle uuid := public.try_uuid(f[2]);
  i public.fleet_issues%rowtype;
begin
  if not public.fleet_issue_path(p_name) or auth.uid() is null then
    return false;
  end if;
  select * into i from public.fleet_issues x
  where x.id = public.try_uuid(f[4]) and x.company_id = v_company and x.vehicle_id = v_vehicle and p_name = any (x.photos);
  if found then
    return public.fleet_issue_can_read(i);
  end if;
  return p_owner = auth.uid()
    and (public.fleet_issue_can_report(v_company, v_vehicle)
         or (public.fleet_can(v_company, 'issues.manage')
             and exists (select 1 from public.company_vehicles cv where cv.id = v_vehicle and cv.company_id = v_company)));
end
$$;

-- Delete. Attached: issues.manage only. Not attached: its uploader.
create function public.fleet_issue_photo_can_delete(p_name text, p_owner uuid)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  f text[] := string_to_array(p_name, '/');
  v_company uuid := public.try_uuid(f[1]);
begin
  if not public.fleet_issue_path(p_name) or auth.uid() is null then
    return false;
  end if;
  if exists (select 1 from public.fleet_issues x where x.id = public.try_uuid(f[4]) and p_name = any (x.photos)) then
    return public.fleet_can(v_company, 'issues.manage')
       and exists (select 1 from public.fleet_issues x where x.id = public.try_uuid(f[4]) and x.company_id = v_company);
  end if;
  return p_owner = auth.uid();
end
$$;
revoke execute on function public.fleet_issue_photo_can_upload(text), public.fleet_issue_photo_can_read(text, uuid),
  public.fleet_issue_photo_can_delete(text, uuid) from public, anon;
grant execute on function public.fleet_issue_photo_can_upload(text), public.fleet_issue_photo_can_read(text, uuid),
  public.fleet_issue_photo_can_delete(text, uuid) to authenticated;

-- The three M1 policies, now branching on the path. Every path that is not an issue photo keeps the
-- M1 expression unchanged.
drop policy fleet_files_insert on storage.objects;
drop policy fleet_files_select on storage.objects;
drop policy fleet_files_delete on storage.objects;
create policy fleet_files_insert on storage.objects for insert to authenticated
  with check (bucket_id = 'fleet-files'
    and case when public.fleet_issue_path(name) then public.fleet_issue_photo_can_upload(name)
             else public.fleet_file_can_write(public.try_uuid((storage.foldername(name))[1]), public.try_uuid((storage.foldername(name))[2])) end);
create policy fleet_files_select on storage.objects for select to authenticated
  using (bucket_id = 'fleet-files'
    and case when public.fleet_issue_path(name) then public.fleet_issue_photo_can_read(name, owner)
             else (public.fleet_can(public.try_uuid((storage.foldername(name))[1]), 'costs.view') or owner = auth.uid()) end);
create policy fleet_files_delete on storage.objects for delete to authenticated
  using (bucket_id = 'fleet-files'
    and case when public.fleet_issue_path(name) then public.fleet_issue_photo_can_delete(name, owner)
             else (public.fleet_can(public.try_uuid((storage.foldername(name))[1]), 'costs.manage') or owner = auth.uid()) end);

-- The photos a request attaches: each the caller's own upload, in this issue's folder, at most 23 hours
-- old (an older one may already be on the cleanup's list). Returns them in the order given, deduplicated.
create function public.fleet_issue_check_photos(p_company uuid, p_vehicle uuid, p_issue uuid, p_photos jsonb)
returns text[]
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_list text[] := '{}';
  v_name text;
  v_prefix text := p_company::text || '/' || p_vehicle::text || '/issues/' || p_issue::text || '/';
  o record;
begin
  if p_photos is null or jsonb_typeof(p_photos) = 'null' then
    return v_list;
  end if;
  if jsonb_typeof(p_photos) <> 'array' then
    perform public.fail('issue_invalid', jsonb_build_object('field', 'photos'));
  end if;
  for v_name in select jsonb_array_elements_text(p_photos) loop
    if v_name = any (v_list) then
      continue;
    end if;
    if not public.fleet_issue_path(v_name) or left(v_name, char_length(v_prefix)) <> v_prefix then
      perform public.fail('issue_invalid', jsonb_build_object('field', 'photos'));
    end if;
    select ob.owner, ob.created_at into o from storage.objects ob where ob.bucket_id = 'fleet-files' and ob.name = v_name;
    if not found or o.owner is distinct from auth.uid() then
      perform public.fail('issue_invalid', jsonb_build_object('field', 'photos'));
    end if;
    if o.created_at < now() - interval '23 hours' then
      perform public.fail('photo_expired');
    end if;
    v_list := v_list || v_name;
  end loop;
  return v_list;
end
$$;
revoke execute on function public.fleet_issue_check_photos(uuid, uuid, uuid, jsonb) from public, anon, authenticated;

